    private void setupTable() {

    model = new DefaultTableModel(
        new Object[][] {},
        new String[] {
            "ID",
            "Student No",
            "Name",
            "Course",
            "Year Level"
        }
    ) {
        @Override
        public boolean isCellEditable(int row, int column) {
            return false;
        }
    };

    tblStudents = new JTable(model);

    tblStudents.setSelectionMode(
        ListSelectionModel.SINGLE_SELECTION
    );

    tblStudents.getColumnModel()
            .getColumn(0)
            .setMinWidth(0);

    tblStudents.getColumnModel()
            .getColumn(0)
            .setMaxWidth(0);

    tblStudents.getColumnModel()
            .getColumn(0)
            .setWidth(0);

    jScrollPane1.setViewportView(tblStudents);

    tblStudents.getSelectionModel()
            .addListSelectionListener(e -> {

                if (!e.getValueIsAdjusting()
                        && tblStudents.getSelectedRow() != -1) {

                    loadSelectedStudent();
                }

            });
    }

    private void loadStudents() {

        model.setRowCount(0);

        String sql = """
            SELECT ID, StudentNo, Name, Course, YearLevel
            FROM Students
            ORDER BY ID
            """;

        try (
            Connection conn = MsConnectAccess.conn();
            PreparedStatement pst = conn.prepareStatement(sql);
            ResultSet rs = pst.executeQuery()
        ) {

            while (rs.next()) {

                model.addRow(new Object[] {
                    rs.getInt("ID"),
                    rs.getString("StudentNo"),
                    rs.getString("Name"),
                    rs.getString("Course"),
                    rs.getInt("YearLevel")
                });
            }

        } catch (SQLException e) {

            JOptionPane.showMessageDialog(
                    this,
                    "Unable to load students:\n" + e.getMessage(),
                    "Database Error",
                    JOptionPane.ERROR_MESSAGE
            );
        }
    }
    
    private void loadSelectedStudent() {

        int row = tblStudents.getSelectedRow();

        if (row == -1) {
            return;
        }

        txtstudentNo.setText(
                model.getValueAt(row, 1).toString()
        );

        txtName.setText(
                model.getValueAt(row, 2).toString()
        );

        cmbCourse.setSelectedItem(
                model.getValueAt(row, 3).toString()
        );

        txtYearLevel.setText(
                model.getValueAt(row, 4).toString()
        );

        btnUpdate.setEnabled(true);
        btnDelete.setEnabled(true);
        btnAdd.setEnabled(false);
    }
    
    private void clearFields() {

        txtstudentNo.setText("");
        txtName.setText("");
        txtYearLevel.setText("");

        if (cmbCourse.getItemCount() > 0) {
            cmbCourse.setSelectedIndex(0);
        }

        txtstudentNo.requestFocus();
    }
