    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        // TODO add your handling code here:String studentNo = txtStudentNo.getText().trim();
        String name = txtName.getText().trim();
        String course = cmbCourse.getSelectedItem().toString();
        String yearText = txtYearLevel.getText().trim();

        if (txtstudentNo.getText().isEmpty()
           || name.isEmpty()
           || yearText.isEmpty()) { 

            JOptionPane.showMessageDialog(
                    this,
                    "Please complete all fields.",
                    "Missing Information",
                    JOptionPane.WARNING_MESSAGE
            );

            return;
        }

        int yearLevel;

        try {
            yearLevel = Integer.parseInt(yearText);
        } catch (NumberFormatException e) {

            JOptionPane.showMessageDialog(
                    this,
                    "Year Level must be a number.",
                    "Invalid Input",
                    JOptionPane.WARNING_MESSAGE
            );

            return;
        }

        String sql = """
            INSERT INTO Students
            (StudentNo, Name, Course, YearLevel)
            VALUES (?, ?, ?, ?)
            """;

        try (
            Connection conn = MsConnectAccess.conn();
            PreparedStatement pst = conn.prepareStatement(sql)
        ) {

            pst.setString(1, txtstudentNo.getText().trim());
            pst.setString(2, name);
            pst.setString(3, course);
            pst.setInt(4, yearLevel);

            pst.executeUpdate();

            JOptionPane.showMessageDialog(
                    this,
                    "Student added successfully!"
            );

            loadStudents();
            clearFields();

        } catch (SQLException e) {

            JOptionPane.showMessageDialog(
                    this,
                    "Unable to add student:\n" + e.getMessage(),
                    "Database Error",
                    JOptionPane.ERROR_MESSAGE
            );
        }
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        // TODO add your handling code here:
        int row = tblStudents.getSelectedRow();

        if (row == -1) {

            JOptionPane.showMessageDialog(
                    this,
                    "Please select a student first.",
                    "No Selection",
                    JOptionPane.WARNING_MESSAGE
            );

            return;
        }

        String studentNo = txtstudentNo.getText().trim();
        String name = txtName.getText().trim();
        String course = cmbCourse.getSelectedItem().toString();
        String yearText = txtYearLevel.getText().trim();

        if (studentNo.isEmpty()
                || name.isEmpty()
                || yearText.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Please complete all fields.",
                    "Missing Information",
                    JOptionPane.WARNING_MESSAGE
            );

            return;
        }

        int yearLevel;

        try {
            yearLevel = Integer.parseInt(yearText);
        } catch (NumberFormatException e) {

            JOptionPane.showMessageDialog(
                    this,
                    "Year Level must be a number.",
                    "Invalid Input",
                    JOptionPane.WARNING_MESSAGE
            );

            return;
        }

        int id = Integer.parseInt(
                model.getValueAt(row, 0).toString()
        );

        String sql = """
            UPDATE Students
            SET StudentNo = ?,
                Name = ?,
                Course = ?,
                YearLevel = ?
            WHERE ID = ?
            """;

        try (
            Connection conn = MsConnectAccess.conn();
            PreparedStatement pst = conn.prepareStatement(sql)
        ) {

            pst.setString(1, studentNo);
            pst.setString(2, name);
            pst.setString(3, course);
            pst.setInt(4, yearLevel);
            pst.setInt(5, id);

            pst.executeUpdate();

            JOptionPane.showMessageDialog(
                    this,
                    "Student updated successfully!"
            );

            loadStudents();
            clearFields();

            btnUpdate.setEnabled(false);
            btnDelete.setEnabled(false);
            btnAdd.setEnabled(true);

        } catch (SQLException e) {

            JOptionPane.showMessageDialog(
                    this,
                    "Unable to update student:\n" + e.getMessage(),
                    "Database Error",
                    JOptionPane.ERROR_MESSAGE
            );
        }
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        // TODO add your handling code here:
        int row = tblStudents.getSelectedRow();

    if (row == -1) {

        JOptionPane.showMessageDialog(
                this,
                "Please select a student first.",
                "No Selection",
                JOptionPane.WARNING_MESSAGE
        );

        return;
    }

    int answer = JOptionPane.showConfirmDialog(
            this,
            "Are you sure you want to delete this student?",
            "Confirm Delete",
            JOptionPane.YES_NO_OPTION,
            JOptionPane.WARNING_MESSAGE
    );

    if (answer != JOptionPane.YES_OPTION) {
        return;
    }

    int id = Integer.parseInt(
            model.getValueAt(row, 0).toString()
    );

    String sql = "DELETE FROM Students WHERE ID = ?";

    try (
        Connection conn = MsConnectAccess.conn();
        PreparedStatement pst = conn.prepareStatement(sql)
    ) {

        pst.setInt(1, id);

        pst.executeUpdate();

        JOptionPane.showMessageDialog(
                this,
                "Student deleted successfully!"
        );

        loadStudents();
        clearFields();

        btnUpdate.setEnabled(false);
        btnDelete.setEnabled(false);
        btnAdd.setEnabled(true);

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
                this,
                "Unable to delete student:\n" + e.getMessage(),
                "Database Error",
                JOptionPane.ERROR_MESSAGE
        );
    }    
    }//GEN-LAST:event_btnDeleteActionPerformed

